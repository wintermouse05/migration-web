CREATE TABLE scott.customers (
    customer_id    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR2(100) NOT NULL,
    email         VARCHAR2(150),
    city          VARCHAR2(50),
    country       VARCHAR2(50) DEFAULT 'Vietnam',
    created_at    DATE DEFAULT SYSDATE,
    status        VARCHAR2(20) DEFAULT 'ACTIVE'
);

CREATE TABLE scott.products (
    product_id    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR2(200) NOT NULL,
    category     VARCHAR2(50),
    price        NUMBER(12, 2) NOT NULL,
    stock        NUMBER(10) DEFAULT 0,
    created_at   DATE DEFAULT SYSDATE
);

CREATE TABLE scott.orders (
    order_id      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  NUMBER(10) NOT NULL,
    order_date   DATE DEFAULT SYSDATE,
    total_amount NUMBER(14, 2) DEFAULT 0,
    status       VARCHAR2(30) DEFAULT 'PENDING',
    shipping_city VARCHAR2(50)
);

CREATE TABLE scott.order_items (
    item_id       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     NUMBER(10) NOT NULL,
    product_id   NUMBER(10) NOT NULL,
    quantity     NUMBER(5) NOT NULL,
    unit_price   NUMBER(12, 2) NOT NULL,
    discount_pct NUMBER(5, 2) DEFAULT 0
);

