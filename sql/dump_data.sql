-- Procedure 1: Cap nhat trang thai don hang
CREATE OR REPLACE PROCEDURE scott.update_order_status(
    p_order_id   IN NUMBER,
    p_new_status IN VARCHAR2
)
IS
    v_old_status VARCHAR2(30);
BEGIN
    IF p_new_status NOT IN ('PENDING', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED') THEN
        RAISE_APPLICATION_ERROR(-20001, 'Invalid status: ' || p_new_status);
    END IF;

    SELECT status INTO v_old_status FROM scott.orders WHERE order_id = p_order_id;

    UPDATE scott.orders
    SET status = p_new_status
    WHERE order_id = p_order_id;

    DBMS_OUTPUT.PUT_LINE('Order ' || p_order_id || ': ' || v_old_status || ' -> ' || p_new_status);
END;
/

-- Procedure 2: Dem khach hang theo quoc gia
CREATE OR REPLACE PROCEDURE scott.get_employee_count(
    p_country       IN  VARCHAR2,
    p_count         OUT NUMBER,
    p_country_name  OUT VARCHAR2
)
IS
BEGIN
    SELECT COUNT(*), NVL(MAX(c.country), 'Unknown')
    INTO p_count, p_country_name
    FROM scott.customers c
    WHERE UPPER(c.country) LIKE '%' || UPPER(p_country) || '%';
END;
/

