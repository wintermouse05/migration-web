CREATE TABLE scott.customers (
    customer_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name  VARCHAR(100) NOT NULL,
    email          VARCHAR(150),
    city           VARCHAR(50),
    country        VARCHAR(50) DEFAULT 'Vietnam',
    created_at     DATE DEFAULT CURRENT_DATE,
    status         VARCHAR(20) DEFAULT 'ACTIVE'
);

CREATE TABLE scott.products (
    product_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name   VARCHAR(200) NOT NULL,
    category       VARCHAR(50),
    price          NUMERIC(12, 2) NOT NULL,
    stock          NUMERIC(10) DEFAULT 0,
    created_at     DATE DEFAULT CURRENT_DATE
);

CREATE TABLE scott.orders (
    order_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    BIGINT NOT NULL,
    order_date     DATE DEFAULT CURRENT_DATE,
    total_amount   NUMERIC(14, 2) DEFAULT 0,
    status         VARCHAR(30) DEFAULT 'PENDING',
    shipping_city  VARCHAR(50)
);

CREATE TABLE scott.order_items (
    item_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT NOT NULL,
    product_id     BIGINT NOT NULL,
    quantity       NUMERIC(5) NOT NULL,
    unit_price     NUMERIC(12, 2) NOT NULL,
    discount_pct   NUMERIC(5, 2) DEFAULT 0
);

-- Foreign Keys
ALTER TABLE scott.orders
    ADD CONSTRAINT fk_orders_customer
    FOREIGN KEY (customer_id) REFERENCES scott.customers(customer_id);

ALTER TABLE scott.order_items
    ADD CONSTRAINT fk_items_order
    FOREIGN KEY (order_id) REFERENCES scott.orders(order_id);

ALTER TABLE scott.order_items
    ADD CONSTRAINT fk_items_product
    FOREIGN KEY (product_id) REFERENCES scott.products(product_id);

