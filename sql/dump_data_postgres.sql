-- Procedure 1: Cap nhat trang thai don hang
CREATE OR REPLACE PROCEDURE scott.update_order_status(
    IN p_order_id NUMERIC,
    IN p_new_status VARCHAR
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_old_status VARCHAR(30);
BEGIN
    IF p_new_status NOT IN ('PENDING', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED') THEN
        RAISE EXCEPTION 'Invalid status: %', p_new_status;
    END IF;

    SELECT status
    INTO v_old_status
    FROM scott.orders
    WHERE order_id = p_order_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Order % not found', p_order_id;
    END IF;

    UPDATE scott.orders
    SET status = p_new_status
    WHERE order_id = p_order_id;

    RAISE NOTICE 'Order %: % -> %', p_order_id, v_old_status, p_new_status;
END;
$$;

-- Procedure 2: Dem khach hang theo quoc gia
CREATE OR REPLACE PROCEDURE scott.get_employee_count(
    IN p_country VARCHAR,
    INOUT p_count BIGINT,
    INOUT p_country_name VARCHAR
)
LANGUAGE plpgsql
AS $$
BEGIN
    SELECT COUNT(*), COALESCE(MAX(c.country), 'Unknown')
    INTO p_count, p_country_name
    FROM scott.customers c
    WHERE UPPER(c.country) LIKE '%' || UPPER(p_country) || '%';
END;
$$;

