-- View 1: Thong tin khach hang + so don hang + tong tien
CREATE OR REPLACE VIEW scott.v_customer_orders AS
SELECT
    c.customer_id,
    c.customer_name,
    c.city,
    c.country,
    c.status,
    COUNT(o.order_id)                           AS total_orders,
    COALESCE(SUM(o.total_amount), 0)            AS total_spent,
    COALESCE(AVG(o.total_amount), 0)            AS avg_order_value,
    COALESCE(MAX(o.total_amount), 0)            AS max_order_value
FROM scott.customers c
LEFT JOIN scott.orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name, c.city, c.country, c.status;

-- View 2: Tom tat san pham + doanh thu + ton kho
CREATE OR REPLACE VIEW scott.v_product_summary AS
SELECT
    p.product_id,
    p.product_name,
    p.category,
    p.price,
    p.stock,
    COALESCE(SUM(oi.quantity), 0) AS total_sold,
    COALESCE(SUM(oi.quantity * oi.unit_price * (1 - COALESCE(oi.discount_pct, 0) / 100)), 0) AS total_revenue
FROM scott.products p
LEFT JOIN scott.order_items oi ON p.product_id = oi.product_id
LEFT JOIN scott.orders o ON oi.order_id = o.order_id
GROUP BY p.product_id, p.product_name, p.category, p.price, p.stock;

