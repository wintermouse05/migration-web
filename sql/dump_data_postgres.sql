-- Function 1: Tinh cap bac khach hang
CREATE OR REPLACE FUNCTION scott.get_customer_level(p_customer_id IN NUMERIC)
RETURNS VARCHAR(20)
LANGUAGE plpgsql
AS $$
DECLARE
    v_total NUMERIC;
    v_level VARCHAR(20);
BEGIN
    SELECT COALESCE(SUM(total_amount), 0)
    INTO v_total
    FROM scott.orders
    WHERE customer_id = p_customer_id AND status <> 'CANCELLED';

    IF v_total >= 50000000 THEN
        v_level := 'GOLD';
    ELSIF v_total >= 20000000 THEN
        v_level := 'SILVER';
    ELSIF v_total >= 5000000 THEN
        v_level := 'BRONZE';
    ELSE
        v_level := 'NEW';
    END IF;

    RETURN v_level;
END;
$$;

-- Function 2: Tinh tong tien don hang (co discount)
CREATE OR REPLACE FUNCTION scott.calculate_order_total(p_order_id IN NUMERIC)
RETURNS NUMERIC
LANGUAGE plpgsql
AS $$
DECLARE
    v_total NUMERIC := 0;
BEGIN
    SELECT COALESCE(SUM(quantity * unit_price * (1 - COALESCE(discount_pct, 0) / 100)), 0)
    INTO v_total
    FROM scott.order_items
    WHERE order_id = p_order_id;

    RETURN ROUND(v_total, 2);
END;
$$;

